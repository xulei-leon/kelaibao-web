import { createHash } from "node:crypto";
import { lstat, mkdir, readFile, realpath, rm, stat, writeFile } from "node:fs/promises";
import { dirname, join, relative, resolve, sep } from "node:path";
import { fileURLToPath } from "node:url";

import sharp from "sharp";

import { responsiveAssets } from "./responsive-assets.config.mjs";

const defaultProjectRoot = resolve(dirname(fileURLToPath(import.meta.url)), "..");

function sourcePath(publicRoot, src) {
  if (!/^\/visual\/image\/[a-z0-9/_-]+\.webp$/i.test(src)) {
    throw new Error(`Responsive asset source is invalid: ${src}`);
  }
  return join(publicRoot, ...src.split("/").filter(Boolean));
}

function assertInside(root, candidate) {
  const path = relative(root, candidate);
  if (!path || path === ".." || path.startsWith(`..${sep}`) || resolve(candidate) === resolve(root)) {
    throw new Error(`Responsive asset path escapes its allowed root: ${candidate}`);
  }
}

function budget(kind, width) {
  if (kind === "feature" && width <= 480) return 100 * 1024;
  if (kind === "hero" && width <= 768) return 120 * 1024;
  if (kind === "hero" && width <= 1600) return 250 * 1024;
  return null;
}

function moduleSource(manifest) {
  return `// Generated by scripts/build-responsive-assets.mjs. Do not edit.\n` +
    `export const RESPONSIVE_ASSETS = ${JSON.stringify(manifest, null, 2)} as const;\n`;
}

export async function buildResponsiveAssets({
  assets = responsiveAssets,
  projectDirectory = defaultProjectRoot,
} = {}) {
  const projectRoot = resolve(projectDirectory);
  const publicRoot = join(projectRoot, "public");
  const sourceRoot = join(publicRoot, "visual", "image");
  const outputRoot = join(publicRoot, "visual", "generated");
  const generatedModule = join(
    projectRoot,
    "src",
    "content",
    "responsive-assets.generated.ts",
  );

  const seen = new Set();
  const prepared = [];
  const resolvedSourceRoot = await realpath(sourceRoot);
  for (const asset of assets) {
    if (!/^[a-z0-9][a-z0-9-]*$/.test(asset.id)) {
      throw new Error(`Responsive asset id is invalid: ${asset.id}`);
    }
    if (seen.has(asset.id)) {
      throw new Error(`Duplicate responsive asset id: ${asset.id}`);
    }
    seen.add(asset.id);
    if (!Array.isArray(asset.widths) || !asset.widths.length) {
      throw new Error(`Responsive asset widths are missing: ${asset.id}`);
    }
    const widths = [...new Set(asset.widths)];
    if (
      widths.some((width) => !Number.isInteger(width) || width <= 0) ||
      widths.length !== asset.widths.length
    ) {
      throw new Error(`Responsive asset widths are invalid: ${asset.id}`);
    }
    const input = sourcePath(publicRoot, asset.src);
    assertInside(sourceRoot, input);
    const inputInfo = await lstat(input);
    if (!inputInfo.isFile() || inputInfo.isSymbolicLink()) {
      throw new Error(`Responsive asset source must be a regular file: ${asset.id}`);
    }
    const resolvedInput = await realpath(input);
    assertInside(resolvedSourceRoot, resolvedInput);
    const bytes = await readFile(resolvedInput);
    let metadata;
    try {
      metadata = await sharp(bytes).metadata();
    } catch {
      throw new Error(`Responsive asset metadata is invalid: ${asset.id}`);
    }
    if (!metadata.width || !metadata.height || metadata.format !== "webp") {
      throw new Error(`Responsive asset metadata is invalid: ${asset.id}`);
    }
    const allowedWidths = widths.filter((width) => width <= metadata.width);
    if (!allowedWidths.length || !allowedWidths.includes(asset.fallbackWidth)) {
      throw new Error(`Responsive asset fallback width is invalid: ${asset.id}`);
    }
    prepared.push({ asset, allowedWidths, bytes, metadata });
  }

  await rm(outputRoot, { recursive: true, force: true });
  await mkdir(outputRoot, { recursive: true });
  const manifest = {};
  for (const { asset, allowedWidths, bytes, metadata } of prepared) {
    const sourceHash = createHash("sha256").update(bytes).digest("hex");
    const hashDirectory = sourceHash.slice(0, 20);
    const outputDirectory = join(outputRoot, asset.id, hashDirectory);
    assertInside(outputRoot, outputDirectory);
    await mkdir(outputDirectory, { recursive: true });
    const variants = [];
    for (const width of allowedWidths) {
      const output = join(outputDirectory, `${width}.webp`);
      await sharp(bytes)
        .rotate()
        .resize({ width, withoutEnlargement: true })
        .webp({ quality: 80, smartSubsample: true })
        .toFile(output);
      const outputInfo = await stat(output);
      const maximum = budget(asset.kind, width);
      if (maximum !== null && outputInfo.size > maximum) {
        throw new Error(
          `Responsive asset ${asset.id} ${width}px exceeds budget: ${outputInfo.size} > ${maximum}`,
        );
      }
      variants.push({
        width,
        src: `/visual/generated/${asset.id}/${hashDirectory}/${width}.webp`,
        byteSize: outputInfo.size,
      });
    }
    manifest[asset.id] = {
      sourceHash,
      sourceWidth: metadata.width,
      sourceHeight: metadata.height,
      fallbackSrc: variants.find(
        (variant) => variant.width === asset.fallbackWidth,
      ).src,
      variants,
    };
  }

  await mkdir(dirname(generatedModule), { recursive: true });
  await writeFile(generatedModule, moduleSource(manifest), "utf8");
  return manifest;
}

if (
  process.argv[1] &&
  resolve(process.argv[1]) === resolve(fileURLToPath(import.meta.url))
) {
  const manifest = await buildResponsiveAssets();
  console.log(`Generated ${Object.keys(manifest).length} responsive asset manifests.`);
}
